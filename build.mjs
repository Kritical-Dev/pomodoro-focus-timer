// Build: assemble the userscript from src/. No dependencies, no network —
// the output is a pure function of the files below, so CI can verify that
// the committed pomodoro.user.js is up to date.
// Usage:  node build.mjs
import fs from 'node:fs';

const read = f => fs.readFileSync(new URL(f, import.meta.url), 'utf8');
const { version } = JSON.parse(read('package.json'));

// Light minification: comments and insignificant whitespace only.
const css = read('src/styles.css')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s+/g, ' ')
  .replace(/\s*([{};,>])\s*/g, '$1')
  .replace(/:\s+/g, ': ')
  .replace(/;}/g, '}')
  .trim();
if (/\d(?:\.\d+)?rem\b/.test(css)) throw new Error('styles.css must not use rem (it follows the page root font-size)');

const MARK = '// @build:strip-below';
const core = read('src/core.js');
if (!core.includes(MARK)) throw new Error('strip marker missing from src/core.js');

const body = [
  "'use strict';",
  '',
  '// Only run in the top frame — one widget per tab.',
  'if (window.top !== window.self) return;',
  '',
  '// Generated by build.mjs from src/ — edit the sources, not this file.',
  'const STYLES = ' + JSON.stringify(css) + ';',
  '',
  core.slice(0, core.indexOf(MARK)).trimEnd(),
  '',
  read('src/main.js').trimEnd(),
].join('\n');

const meta = read('src/meta.txt');
if (!meta.includes('__VERSION__')) throw new Error('__VERSION__ placeholder missing from src/meta.txt');

const out =
  meta.replace('__VERSION__', () => version).trimEnd() + '\n\n' +
  '(function () {\n' +
  body.split('\n').map(l => (l ? '  ' + l : l)).join('\n') + '\n' +
  '})();\n';

fs.writeFileSync(new URL('pomodoro.user.js', import.meta.url), out);
console.log('Built pomodoro.user.js v' + version + ' (' + (out.length / 1024).toFixed(1) + ' KB, CSS ' + (css.length / 1024).toFixed(1) + ' KB)');
